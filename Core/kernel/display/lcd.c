static void lcd_internal_testgrid() {
	// draw boxes with the 256 colours, 16 rows, 16 columns, at 16x16px boxes
	const int boxsize = 8;
	int bx, by;
	for (bx = 0; bx < 480; bx++) {
		for (by = 0; by < 320; by += 20) {
			lcd_internal_buffer_draw_pixel(bx, by, 29);
		}
	}

	for (bx = 0; bx < 480; bx += 20) {
		for (by = 0; by < 320; by++) {
			lcd_internal_buffer_draw_pixel(bx, by, 29);
		}
	}

	for (bx = 0; bx < 16; bx++) {
		for (by = 0; by < 16; by++) {
			for (int x = 0; x < 20; x++) {
				for (int y = 0; y < 20; y++)
					lcd_internal_buffer_draw_pixel((bx * boxsize) + x, (by * boxsize) + y, 82);
			}
		}
	}
}

