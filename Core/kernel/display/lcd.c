// this is to be used ONLY when the DMA2D is not being used. this is a direct to register pixel set
void bios_text(long x, long y, const char *textptr) {
	signed long j;
    const unsigned char *pixeldata;
    unsigned char pixdat;

    while (*textptr) {
    	uint8_t ch = (uint8_t)(unsigned char)*textptr++;
        pixeldata = bios_font[ch]; // Get pointer to 8-byte character
        for (j = 0; j < 8; ++j) {
            pixdat = pixeldata[j];
            // Double-height: each row gets plotted twice on adjacent Y positions
            if (pixdat & 0x01) { HWLCD_PIXEL(x, y + 0); HWLCD_PIXEL(x, y + 1); }
            if (pixdat & 0x02) { HWLCD_PIXEL(x, y + 2); HWLCD_PIXEL(x, y + 3); }
            if (pixdat & 0x04) { HWLCD_PIXEL(x, y + 4); HWLCD_PIXEL(x, y + 5); }
            if (pixdat & 0x08) { HWLCD_PIXEL(x, y + 6); HWLCD_PIXEL(x, y + 7); }
            if (pixdat & 0x10) { HWLCD_PIXEL(x, y + 8); HWLCD_PIXEL(x, y + 9); }
            if (pixdat & 0x20) { HWLCD_PIXEL(x, y +10); HWLCD_PIXEL(x, y +11); }
            if (pixdat & 0x40) { HWLCD_PIXEL(x, y +12); HWLCD_PIXEL(x, y +13); }
            if (pixdat & 0x80) { HWLCD_PIXEL(x, y +14); HWLCD_PIXEL(x, y +15); }
            x++;
        }
    }
}

